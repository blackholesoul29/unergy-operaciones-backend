# ── Ejecución ──────────────────────────────────────────────────────────────────

def run(dry_run: bool = False):
    engine = create_engine(settings.DATABASE_URL)
    updated, not_found = [], []

    with Session(engine) as db:
        for nombre, vals in SIMULACIONES.items():
            # Buscar por nombre_comercial o sub_project (insensible a mayúsculas)
            proyecto = db.query(Proyecto).filter(
                or_(
                    func.lower(Proyecto.nombre_comercial).contains(nombre.lower()),
                    func.lower(Proyecto.sub_project).contains(nombre.lower()),
                )
            ).first()

            if not proyecto:
                print(f"  ⚠  NO ENCONTRADO: {nombre!r}")
                not_found.append(nombre)
                continue

            found_name = proyecto.nombre_comercial or proyecto.sub_project
            print(f"  ✓  {nombre!r}  →  [{proyecto.id}] {found_name!r}")

            if not dry_run:
                proyecto.p50_mensual_kwh = vals["p50"]
                proyecto.p90_mensual_kwh = vals["p90"]
                proyecto.p99_mensual_kwh = vals["p99"]
                updated.append(found_name)

        if not dry_run:
            db.commit()

    print()
    if dry_run:
        print(f"[dry-run] Se actualizarían {len(SIMULACIONES) - len(not_found)} proyectos.")
    else:
        print(f"✅ Actualizados: {len(updated)}")
    if not_found:
        print(f"❌ No encontrados ({len(not_found)}): {', '.join(not_found)}")


if __name__ == "__main__":
    dry = "--dry-run" in sys.argv
    if dry:
        print("=== DRY RUN — no se guardará nada ===\n")
    else:
        print("=== Aplicando simulaciones P50/P90/P99 ===\n")
    run(dry_run=dry)
